exports.update = async (req, res) => {
    try {
        const { id } = req.params;
        const { sensorCatName, sensorCatDes } = req.body;

        // Ensure all necessary data is provided


        const updateQuery = `
            UPDATE sensor_categories
            SET sensorCategoryName = ?, sensorCategoryDescription = ?
            WHERE id = ?`;
        const values = [sensorCatName, sensorCatDes, id];

        const [uRows] = await connection.execute(updateQuery, values);

        if (uRows.affectedRows > 0) {
            return res.status(200).json({ success: true, message: "Data updated successfully" });
        } else {
            throw new CustomError("No matching record found or no changes made", 404);
        }

    } catch (err) {
        return res.status(err.statusCode || 500).json({ success: false, message: err.message || 'An error occurred' });
    }
};




exports.delete = async (req, res) => {
    try {
        const { id } = req.params;

        const deleteQuery = `DELETE FROM sensor_categories WHERE id = ?`;
        const [result] = await connection.execute(deleteQuery, [id]);

        if (result.affectedRows > 0) {
            return res.status(200).json({ success: true, message: "Record deleted successfully" });
        } else {
            return res.status(404).json({ success: false, message: "Record not found" });
        }

    } catch (err) {
        return res.status(err.statusCode || 500).json({ success: false, message: err.message || 'An error occurred' });
    }
};





