exports.showData = async (req, res) => {
    try {
        const newData = req.body;
        const showQuery = `SELECT a.*,d.departmentName as dname,s.Section as Sname,at.AssetTypeView  as Typename  FROM assettable a 
        INNER JOIN  departments d on d.id=a.Department 
        INNER JOIN  sectiontable s on s.id=a.Section 
        INNER JOIN  assettype at on at.id=a.AssetType 
        WHERE a.Department=? OR a.Section=? OR a.AssetType=?`;

        const values = [
            newData.Department,
            newData.Section,
            newData.AssetType
        ];
        const [rows] = await connection.execute(showQuery, values);

        if (rows.length > 0) {
            return res.status(200).json({ success: true, data: rows });
        } else {
            return res.status(404).json({ success: false, message: "Data not found" });
        }

    } catch (err) {
        return res.status(err.statusCode || 500).json({ success: false, message: err.message || 'An error occurred' });
    }
};





